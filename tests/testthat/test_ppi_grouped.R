test_that("grouped fits and contrasts match independent per-group fits", {
  set.seed(31); n <- 90; seed <- rnorm(n)
  p <- cbind(A=sin(seq_len(n)/5), B=cos(seq_len(n)/9))
  d <- ppi_design(seed, psych=p, hrf=c(0,1,.5), microtime=1, run_effects="shared")
  e <- sapply(c(.7,.1,.7,.1), function(a) as.numeric(arima.sim(list(ar=a),n=n)))
  colnames(e) <- paste0("target",1:4); labels <- c("high","low","high","low")
  fit <- ppi_fit(e,d,noise="fmriAR",noise_control=list(pooling="parcel",parcels=labels,p=1L))
  expect_identical(fit$groups, labels)
  for (g in unique(labels)) {
    idx <- which(labels==g)
    ref <- ppi_fit(e[,idx,drop=FALSE],d,noise="fmriAR",noise_control=list(pooling="global",p=1L))
    expect_equal(fit$coefficients[,idx],ref$coefficients)
    expect_equal(fit$standard_errors[,idx],ref$standard_errors)
    expect_equal(fit$sigma2[idx],ref$sigma2)
    tc <- ppi_contrast(fit,c(A=1,B=-1)); tr <- ppi_contrast(ref,c(A=1,B=-1))
    expect_equal(tc$estimate[,idx,drop=FALSE],tr$estimate)
    expect_equal(tc$standard_error[,idx,drop=FALSE],tr$standard_error)
    expect_equal(tc$p_value[,idx,drop=FALSE],tr$p_value)
    contrast <- rbind(c(A=1,B=0),c(A=0,B=1))
    fc <- ppi_contrast(fit,contrast,test="F"); fr <- ppi_contrast(ref,contrast,test="F")
    expect_equal(unname(fc$statistic[idx]),unname(fr$statistic))
    expect_equal(unname(fc$p_value[idx]),unname(fr$p_value))
  }
  expect_error(ppi_fit(e,d,noise_control=list(pooling="parcel",parcels=c(1,2,NA,4))),"label")
  expect_error(ppi_fit(e,d,noise_control=list(pooling="parcel",parcels=1:3)),"label")
  targetwise <- ppi_fit(e,d,noise_control=list(pooling="parcel",parcels=seq_len(ncol(e)),p=1L))
  expect_length(targetwise$group_fits,4)
})

test_that("frame adapter validates TR, runs and acquisition mask", {
  skip_if_not_installed("fmrireg"); skip_if_not_installed("fmridataset")
  set.seed(7); n <- 40; Y <- matrix(rnorm(n*2),n); p <- matrix(rep(c(0,1),20),ncol=1)
  frame <- fmrireg::matrix_frame(datamat=Y,TR=2,run_length=n)
  d <- ppi_design(rnorm(n),psych=p,TR=2,runs=rep("run-1",n),hrf=c(0,1),microtime=1)
  expect_equal(ppi_fit(frame,d,noise="iid")$coefficients,ppi_fit(Y,d,noise="iid")$coefficients)
  bad <- d; bad$TR <- 1; expect_error(ppi_fit(frame,bad,noise="iid"),"TR")
  bad <- d; bad$runs <- rep("other",n); expect_error(ppi_fit(frame,bad,noise="iid"),"run labels")
  bad <- d; bad$keep[2] <- FALSE; expect_error(ppi_fit(frame,bad,noise="iid"),"censor")
})

test_that("targets identical to the seed do not abort grouped noise fits", {
  set.seed(31); n <- 90; seed <- rnorm(n)
  p <- cbind(A=sin(seq_len(n)/5), B=cos(seq_len(n)/9))
  d <- ppi_design(seed, psych=p, hrf=c(0,1,.5), microtime=1, run_effects="shared")
  e <- sapply(c(.7,.1,.7,.1), function(a) as.numeric(arima.sim(list(ar=a),n=n)))
  colnames(e) <- paste0("target",1:4); e[,1] <- seed
  expect_warning(fit <- ppi_fit(e,d,noise_control=list(pooling="parcel",parcels=seq_len(4),p=1L)),
                 "target1 \\(parcel '1'\\).*IID errors: '1'")
  expect_identical(fit$group_fits[["1"]]$noise, "iid")
  expect_null(fit$noise_plan[["1"]])
  expect_identical(unname(fit$degenerate), c(TRUE,FALSE,FALSE,FALSE))
  ref <- ppi_fit(e[,2,drop=FALSE],d,noise_control=list(p=1L))
  expect_equal(fit$coefficients[,2],ref$coefficients[,1])
  expect_true(all(is.finite(ppi_contrast(fit,c(A=1))$estimate)))
  # Mixed groups and global pooling estimate noise from the remaining targets.
  expect_warning(mixed <- ppi_fit(e,d,noise_control=list(pooling="parcel",parcels=c(1,1,2,2),p=1L)),"excluded")
  ref <- ppi_fit(e[,2,drop=FALSE],d,noise_control=list(p=1L))
  expect_equal(mixed$standard_errors[,2],ref$standard_errors[,1])
  expect_equal(mixed$group_fits[["1"]]$noise_plan$phi,ref$noise_plan$phi)
  expect_warning(global <- ppi_fit(unname(e),d,noise_control=list(p=1L)),"excluded from noise estimation: 1\\.")
  expect_identical(global$noise,"fmriAR")
  expect_warning(alone <- ppi_fit(e[,1,drop=FALSE],d,noise_control=list(p=1L)),"using IID errors")
  expect_identical(alone$noise,"iid")
})

