args <- commandArgs(TRUE)
pkgload::load_all(args[1], quiet=TRUE)
res <- testthat::test_dir(file.path(args[1], "tests", "testthat"), reporter="summary", stop_on_failure=FALSE)
saveRDS(res, file.path(args[2], "suite-results.rds"))
d <- as.data.frame(res)
write.csv(d[, intersect(c("file","test","nb","failed","skipped","error","warning","passed"), names(d))], file.path(args[2],"suite-results.csv"),row.names=FALSE)
print(colSums(d[, intersect(c("nb","failed","skipped","error","warning","passed"), names(d))]))
print(sessionInfo())
quit(status=as.integer(any(d$failed > 0 | d$error)))
